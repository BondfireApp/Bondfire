import assert from 'node:assert/strict';
import {sql,call} from './private-storage-regression.mjs';
import {encryptPrivate,decryptPrivate} from '../src/lib/privateCrypto.js';
const id='singleton-migration',key=crypto.getRandomValues(new Uint8Array(32));
sql.prepare('INSERT INTO orgs VALUES(?,?,0)').run(id,'PRIVATE org');
sql.prepare("INSERT INTO org_memberships(org_id,user_id,role,created_at) VALUES(?,'owner','owner',0)").run(id);
const wrap=sql.prepare('SELECT wrapped_key FROM org_key_wrapped LIMIT 1').get().wrapped_key;
sql.prepare('INSERT INTO org_key_wrapped(org_id,user_id,wrapped_key) VALUES(?,?,?)').run(id,'owner',wrap);
sql.exec('CREATE TABLE newsletter_settings(org_id TEXT PRIMARY KEY,enabled INTEGER,list_address TEXT,blurb TEXT,updated_at INTEGER)');
sql.prepare('INSERT INTO newsletter_settings VALUES(?,1,?,?,0)').run(id,'PRIVATE@example.test','PRIVATE blurb');
const base='/api/orgs/'+id+'/privacy';
await call(base+'/begin',{body:{keyCheck:await encryptPrivate(key,{check:'bondfire-private-mode'},id,'key-check',id)}});
let page=await call(base+'/source?kind=newsletter/settings');assert.equal(page.records[0].row.id,id);
let record=page.records[0];
assert.throws(()=>sql.prepare('UPDATE newsletter_settings SET blurb=? WHERE org_id=?').run('new plaintext',id),/PRIVATE_LEGACY_WRITE_FORBIDDEN/);
record={...record,sourceHash:'stale'};
await call(base+'/record',{body:{kind:'newsletter/settings',id,sourceHash:record.sourceHash,ciphertext:await encryptPrivate(key,record.row,id,'newsletter/settings',id)}},409);
page=await call(base+'/source?kind=newsletter/settings');record=page.records[0];
await call(base+'/record',{body:{kind:'newsletter/settings',id,sourceHash:record.sourceHash,ciphertext:await encryptPrivate(key,record.row,id,'newsletter/settings',id)}});
assert.equal((await call(base+'/source?kind=newsletter/settings')).records.length,0);
assert.equal(sql.prepare('SELECT list_address FROM newsletter_settings WHERE org_id=?').get(id).list_address,null);
const stored=sql.prepare("SELECT ciphertext FROM org_private_records WHERE org_id=? AND kind='newsletter/settings'").get(id);
assert.equal((await decryptPrivate(key,stored.ciphertext,id,'newsletter/settings',id)).list_address,'PRIVATE@example.test');
console.log('PASS: singleton newsletter migration preserves content, detects concurrent source changes, and scrubs plaintext');
