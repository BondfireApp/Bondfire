import assert from 'node:assert/strict';
import {env,sql,call} from './private-storage-regression.mjs';
import {encryptPrivate} from '../src/lib/privateCrypto.js';
import {selectPublicFields} from '../shared/publicProjection.js';
const org=sql.prepare("SELECT org_id FROM org_private_mode WHERE org_id NOT IN ('legacy','file-legacy')").get().org_id;
const base='/api/orgs/'+org;
const key=crypto.getRandomValues(new Uint8Array(32));
const kv=new Map();env.BF_PUBLIC={get:async k=>kv.get(k)||null,put:async(k,v)=>kv.set(k,v),delete:async k=>kv.delete(k)};
await call(base+'/privacy/public-slug',{body:{slug:'public-test'},user:'member'},403);
await call(base+'/privacy/public-slug',{body:{slug:'public-test'}});
const config={enabled:true,slug:'public-test',title:'Published title',show_needs:true};
const cc=await encryptPrivate(key,config,org,'public/config',org);
await call(base+'/public/config/'+org,{body:{ciphertext:cc,revision:0}});
await call('/api/public/public-test',{},404);
await call(base+'/privacy/publish',{body:{kind:'public/config',id:org,revision:1,public:config}});
await call(base+'/privacy/publish',{body:{kind:'public/config',id:org,revision:1,public:{...config,website_link:{label:'Link',url:'https://example.test',privateNote:'NEVER_PUBLISH'}}}},400);
assert.equal((await call('/api/public/public-test',{user:'outsider'})).public.title,'Published title');
const id=crypto.randomUUID();
const privateRecord={title:'Public need',description:'Selected description',is_public:true,notes:'NEVER_PUBLISH_PRIVATE_NOTES',phone:'NEVER_PUBLISH_PHONE'};
await call(base+'/needs',{body:{id,revision:0,ciphertext:await encryptPrivate(key,privateRecord,org,'needs',id)}});
await call(base+'/privacy/publish',{body:{kind:'needs',id,revision:1,public:privateRecord}},400);
const selected=selectPublicFields('needs',privateRecord);
await call(base+'/privacy/publish',{body:{kind:'needs',id,revision:1,public:selected},user:'member'},403);
await call(base+'/privacy/publish',{body:{kind:'needs',id,revision:1,public:selected}});
const publicList=await call('/api/public/public-test/needs',{user:'outsider'});
assert.equal(publicList.needs.length,1);assert.equal(publicList.needs[0].title,'Public need');
assert(!JSON.stringify(publicList).includes('NEVER_PUBLISH'));
assert(!JSON.stringify(sql.prepare('SELECT * FROM org_public_projections').all()).includes('NEVER_PUBLISH'));
await call(base+'/needs/'+id,{method:'PUT',body:{revision:1,ciphertext:await encryptPrivate(key,{...privateRecord,title:'Private next draft'},org,'needs',id)}});
await call(base+'/privacy/publish',{body:{kind:'needs',id,revision:1,public:{...selected,title:'Stale publication'}}},409);
assert.equal((await call('/api/public/public-test/needs')).needs[0].title,'Public need');
await call(base+'/privacy/publish',{body:{kind:'needs',id,revision:2,public:null}});
assert.equal((await call('/api/public/public-test/needs')).needs.length,0);
await call(base+'/privacy/publish',{body:{kind:'needs',id,revision:2,public:selected}});
await call(base+'/needs/'+id,{method:'DELETE',body:{revision:2}});
assert.equal((await call('/api/public/public-test/needs')).needs.length,0);
await call(base+'/privacy/publish',{body:{kind:'public/config',id:org,revision:1,public:null}});
await call('/api/public/public-test',{},404);
console.log('PASS: explicit selected-field publication, encrypted originals, admin-only release, stale-publication rejection, unpublishing and deletion.');
