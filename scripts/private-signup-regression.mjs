import assert from 'node:assert/strict';
import {env,sql} from './private-storage-regression.mjs';
import {onRequestPost as register} from '../functions/api/auth/register.js';
for(const column of ['email TEXT','name TEXT','password_hash TEXT','created_at INTEGER'])sql.exec('ALTER TABLE users ADD COLUMN '+column);
sql.exec('CREATE UNIQUE INDEX users_email ON users(email); CREATE TABLE refresh_tokens(id TEXT PRIMARY KEY,user_id TEXT,token_hash TEXT,expires_at INTEGER)');
const request=body=>new Request('https://example.test/api/auth/register',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)});
const orgCount=sql.prepare('SELECT COUNT(*) n FROM orgs').get().n;
const input={email:'new@example.test',password:'separate login credential',name:'Account name'};
let res=await register({env,request:request({...input,orgName:'SECRET legacy org'})});
assert.equal(res.status,400);
assert(!sql.prepare('SELECT * FROM users WHERE email=?').get(input.email));
res=await register({env,request:request(input)});
assert.equal(res.status,200);assert(res.headers.get('set-cookie'));
const data=await res.json();assert.equal(data.requires_org_setup,true);assert(!data.org);
assert.equal(sql.prepare('SELECT COUNT(*) n FROM orgs').get().n,orgCount);
const user=sql.prepare('SELECT * FROM users WHERE email=?').get(input.email);
assert(user);assert.notEqual(user.password_hash,input.password);
assert.equal(sql.prepare('SELECT COUNT(*) n FROM org_memberships WHERE user_id=?').get(user.id).n,0);
assert(sql.prepare('SELECT * FROM refresh_tokens WHERE user_id=?').get(user.id));
res=await register({env,request:request(input)});assert.equal(res.status,409);
sql.exec("CREATE TRIGGER reject_refresh BEFORE INSERT ON refresh_tokens BEGIN SELECT RAISE(ABORT,'injected failure'); END");
res=await register({env,request:request({...input,email:'retry@example.test'})});assert.equal(res.status,500);
assert(!sql.prepare('SELECT * FROM users WHERE email=?').get('retry@example.test'));
sql.exec('DROP TRIGGER reject_refresh');
res=await register({env,request:request({...input,email:'retry@example.test'})});assert.equal(res.status,200);
console.log('PASS: signup creates only account and session; plaintext org rejected; session failure rolls back account and permits retry');
